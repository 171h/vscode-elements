// 仅执行仓库中已审核的静态示例；不接受外部 HTML 或 JavaScript。
export function previewDocument(
  example,
  {base = '/', theme = 'light', size = 'medium'} = {}
) {
  const tokens = {
    '--vscode-font-family': 'Segoe UI, Microsoft YaHei, sans-serif',
    '--vscode-font-size': '13px',
    '--vscode-font-weight': 'normal',
    '--vscode-focusBorder': '#0078d4',
    '--vscode-button-background': '#0078d4',
    '--vscode-button-foreground': '#ffffff',
    '--vscode-button-hoverBackground': '#006cbe',
    '--vscode-progressBar-background': '#0078d4',
    ...themeTokens[theme],
  };
  const css = Object.entries(tokens)
    .map(([key, value]) => `${key}:${value}`)
    .join(';');
  return `<!doctype html><html lang="zh-CN"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><link id="vscode-codicon-stylesheet" rel="stylesheet" href="${base}assets/codicon.css"><style>:root{${css};color-scheme:${theme === 'light' ? 'light' : 'dark'}}*{box-sizing:border-box}body{margin:0;padding:24px;background:var(--vscode-editor-background);color:var(--vscode-foreground);font:13px var(--vscode-font-family)}p{line-height:1.7}output{display:block;margin-top:16px;white-space:pre-wrap;overflow-wrap:anywhere}vscode-textfield,vscode-textarea,vscode-single-select,vscode-multi-select{margin:8px 0;max-width:100%}vscode-label{display:block}vscode-tab-panel{padding:12px}fieldset{margin:8px 0}vscode-fieldset{display:block;margin:8px 0}${example.css || ''}</style></head><body class="vscode-${theme === 'light' ? 'light' : theme === 'contrast' ? 'high-contrast' : 'dark'}">${example.html}<script type="module">import '${base}assets/nusys-ui.js';document.querySelectorAll('[class],body').forEach(el=>el.style.setProperty('--vsc-form-control-size','${size}'));document.querySelectorAll('*').forEach(el=>{if(el.localName.startsWith('vscode-') && 'size' in el)el.size='${size}';if(el.localName==='fieldset')el.setAttribute('size','${size}');});await Promise.all(Array.from(document.querySelectorAll('*')).map(el=>el.updateComplete));${example.js || ''}await Promise.all(Array.from(document.querySelectorAll('*')).map(el=>el.updateComplete));await new Promise(requestAnimationFrame);document.documentElement.dataset.ready='true';<\/script></body></html>`;
}
